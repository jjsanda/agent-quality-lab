"""In-process, deterministic telemetry — the default offline/eval transport.

Logs are loaded from ``data/telemetry/logs.json`` (some lines deliberately carry prompt-injection
so the harness can prove resistance); metric series are generated by a fixed function of
(metric, index); runbooks are read from ``data/runbooks/<slug>.md``; tickets are minted from the
injected :class:`~aql.domain.clock.IdGenerator`. There is no clock, no RNG, and no network, so the
same call always returns the same result.
"""

from __future__ import annotations

import json
import math
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from aql.domain.clock import IdGenerator
from aql.domain.tools_schema import (
    LogLine,
    MetricPoint,
    OpenTicketArgs,
    OpenTicketResult,
    QueryMetricsArgs,
    QueryMetricsResult,
    ReadRunbookArgs,
    RunbookResult,
    SearchLogsArgs,
    SearchLogsResult,
)

__all__ = ["FakeTelemetryClient"]

# Fixed reference instant so generated metric timestamps are reproducible.
_FAKE_NOW = datetime(2026, 6, 30, 11, 0, 0, tzinfo=UTC)

# (baseline, amplitude, unit) per metric; unknown metrics fall back to the last entry.
_METRIC_PROFILE: dict[str, tuple[float, float, str]] = {
    "latency_p99_ms": (2150.0, 60.0, "ms"),
    "error_rate": (0.06, 0.015, "ratio"),
    "cpu_saturation_pct": (86.0, 4.0, "percent"),
    "restart_count": (5.0, 2.0, "count"),
    "requests_per_s": (320.0, 25.0, "rps"),
}
_DEFAULT_PROFILE = (100.0, 5.0, "unit")


class FakeTelemetryClient:
    """A reproducible :class:`~aql.adapters.tools.base.TelemetryClient` over local fixtures."""

    def __init__(self, *, data_dir: Path, id_gen: IdGenerator) -> None:
        self._data_dir = data_dir
        self._id_gen = id_gen
        self._logs = self._load_logs(data_dir / "telemetry" / "logs.json")

    @staticmethod
    def _load_logs(path: Path) -> dict[str, list[LogLine]]:
        if not path.is_file():
            return {}
        raw: dict[str, list[dict[str, Any]]] = json.loads(path.read_text(encoding="utf-8"))
        logs: dict[str, list[LogLine]] = {}
        for service, entries in raw.items():
            logs[service] = [
                LogLine.model_validate({"service": service, **entry}) for entry in entries
            ]
        return logs

    async def search_logs(self, args: SearchLogsArgs) -> SearchLogsResult:
        needle = args.query.lower()
        matched = [
            line
            for line in self._logs.get(args.service, [])
            if needle in f"{line.level} {line.message}".lower()
        ]
        shown = matched[: args.limit]
        return SearchLogsResult(
            lines=shown, total_matched=len(matched), truncated=len(matched) > len(shown)
        )

    async def query_metrics(self, args: QueryMetricsArgs) -> QueryMetricsResult:
        base, amplitude, unit = _METRIC_PROFILE.get(args.metric, _DEFAULT_PROFILE)
        points = 12
        series = [
            MetricPoint(
                t=_FAKE_NOW - timedelta(minutes=5 * (points - 1 - i)),
                v=round(base + amplitude * math.sin(i / 2.0), 3),
            )
            for i in range(points)
        ]
        return QueryMetricsResult(
            metric=args.metric, unit=unit, aggregation=args.aggregation, series=series
        )

    async def read_runbook(self, args: ReadRunbookArgs) -> RunbookResult:
        for slug in (args.slug, "general-incident-response"):
            path = self._data_dir / "runbooks" / f"{slug}.md"
            if path.is_file():
                content = path.read_text(encoding="utf-8")
                title = next(
                    (ln.lstrip("# ").strip() for ln in content.splitlines() if ln.startswith("# ")),
                    slug,
                )
                return RunbookResult(slug=args.slug, title=title, content=content, version="v1")
        return RunbookResult(
            slug=args.slug,
            title="Runbook not found",
            content=f"No runbook is available for slug {args.slug!r}.",
            version="v0",
        )

    async def open_ticket(self, args: OpenTicketArgs) -> OpenTicketResult:
        ticket_id = self._id_gen.new_id("TCK-")
        return OpenTicketResult(
            ticket_id=ticket_id,
            url=f"https://tickets.local/{ticket_id}",
            status="escalated" if args.escalate else "open",
        )

    async def healthy(self) -> bool:
        return True

    async def aclose(self) -> None:
        return None
