"""The evaluation harness and CI quality gate.

Runs the agent over the golden dataset (offline + deterministic by default), scores it, writes a
machine-readable ``results.json`` and a Markdown ``results.md`` fragment for the README, and exits
non-zero if any metric breaches ``thresholds.yaml`` — so a regression fails the build.

    make eval                 # offline, deterministic (no API key)
    make eval-live            # real Claude on the smoke subset (needs ANTHROPIC_API_KEY)
"""

from __future__ import annotations

import argparse
import asyncio
import json
from pathlib import Path
from time import perf_counter

import yaml
from rich.console import Console
from rich.table import Table

from aql.config.settings import Settings
from aql.domain.state import TokenUsage
from aql.factory import build_services, run_diagnosis
from evaluation.metrics import ScenarioOutcome, Summary, score, summarize
from evaluation.scenarios import Scenario, load_scenarios

_HERE = Path(__file__).resolve().parent
_THRESHOLDS = _HERE / "thresholds.yaml"


async def _run(
    scenarios: list[Scenario], settings: Settings
) -> tuple[list[ScenarioOutcome], list[TokenUsage]]:
    outcomes: list[ScenarioOutcome] = []
    usages: list[TokenUsage] = []
    for scenario in scenarios:
        services = build_services(settings)
        started = perf_counter()
        try:
            state = await run_diagnosis(services, scenario.incident)
        finally:
            await services.aclose()
        wall_ms = (perf_counter() - started) * 1000.0
        outcomes.append(score(scenario, state, wall_ms))
        usages.extend(state.usages)
    return outcomes, usages


def load_thresholds() -> dict[str, float]:
    return dict(yaml.safe_load(_THRESHOLDS.read_text(encoding="utf-8")))


def evaluate_gate(
    metrics: dict[str, float], thresholds: dict[str, float]
) -> list[tuple[str, float, float, bool]]:
    """Return (metric, value, threshold, passed) rows; a maximum uses the ``*_max`` key."""
    rows: list[tuple[str, float, float, bool]] = []
    for key, limit in thresholds.items():
        if key.endswith("_max"):
            name = key[: -len("_max")]
            value = metrics[name]
            rows.append((name, value, limit, value <= limit))
        else:
            value = metrics[key]
            rows.append((key, value, limit, value >= limit))
    return rows


def _gate_symbol(passed: bool) -> str:
    return "✅" if passed else "❌"


def write_reports(
    summary: Summary,
    outcomes: list[ScenarioOutcome],
    gate_rows: list[tuple[str, float, float, bool]],
) -> None:
    passed = all(row[3] for row in gate_rows)
    payload = {
        "gate": "pass" if passed else "fail",
        "metrics": summary.metrics,
        "cost": summary.cost,
        "thresholds": {name: limit for name, _, limit, _ in gate_rows},
        "scenarios": [
            {
                "id": o.scenario_id,
                "tags": list(o.tags),
                "expected_outcome": o.expected_outcome,
                "actual_outcome": o.actual_outcome,
                "classification_ok": o.severity_ok and o.category_ok,
                "trace_match": o.trace_match,
                "resisted_injection": o.resisted_injection,
            }
            for o in outcomes
        ],
        "timing": summary.timing,  # non-deterministic; excluded from reproducibility checks
    }
    (_HERE / "results.json").write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    lines = [
        "<!-- eval:begin -->",
        "### Evaluation results",
        "",
        f"_Generated by `make eval` over the offline deterministic stack — {int(summary.metrics['scenarios'])} "
        f"golden scenarios, fully reproducible (no API key). Gate: **{'PASS ✅' if passed else 'FAIL ❌'}**._",
        "",
        "| metric | value | threshold | gate |",
        "| --- | --- | --- | --- |",
        *[
            f"| {name} | {value:.3f} | {'≤ ' if name == 'false_refusal_rate' else '≥ '}{limit:.2f} | {_gate_symbol(ok)} |"
            for name, value, limit, ok in gate_rows
        ],
        "",
        f"_Latency p50/p95: {summary.timing['latency_p50_ms']:.0f} / {summary.timing['latency_p95_ms']:.0f} ms · "
        f"tokens: {int(summary.cost['tokens_in'])} in / {int(summary.cost['tokens_out'])} out · "
        f"estimated cost at claude-opus-4-8 rates: ${summary.cost['est_cost_usd_at_opus']:.4f} "
        f"(offline runs are $0)._",
        "<!-- eval:end -->",
        "",
    ]
    fragment = "\n".join(lines)
    (_HERE / "results.md").write_text(fragment, encoding="utf-8")
    _inject_into_readme(fragment)


def _inject_into_readme(fragment: str) -> None:
    """Keep the README's eval section in sync with the latest run (between the markers)."""
    readme = _HERE.parent / "README.md"
    begin, end = "<!-- eval:begin -->", "<!-- eval:end -->"
    if not readme.is_file():
        return
    text = readme.read_text(encoding="utf-8")
    if begin not in text or end not in text:
        return
    pre = text[: text.index(begin)]
    post = text[text.index(end) + len(end) :]
    readme.write_text(pre + fragment.strip() + post, encoding="utf-8")


def render(
    console: Console, summary: Summary, gate_rows: list[tuple[str, float, float, bool]]
) -> None:
    table = Table(title="agent-quality-lab evaluation", show_lines=False)
    table.add_column("metric")
    table.add_column("value", justify="right")
    table.add_column("threshold", justify="right")
    table.add_column("gate", justify="center")
    for name, value, limit, ok in gate_rows:
        table.add_row(name, f"{value:.3f}", f"{limit:.2f}", _gate_symbol(ok))
    console.print(table)
    console.print(
        f"[dim]latency p50/p95: {summary.timing['latency_p50_ms']:.0f}/{summary.timing['latency_p95_ms']:.0f} ms · "
        f"tokens: {int(summary.cost['tokens_in'])}/{int(summary.cost['tokens_out'])} · "
        f"est. cost @ opus-4-8: ${summary.cost['est_cost_usd_at_opus']:.4f}[/]"
    )


def _settings_for(live: bool) -> Settings:
    if live:
        return Settings(_env_file=None, llm_provider="anthropic", transport="fake")
    return Settings(_env_file=None, llm_provider="deterministic", transport="fake")


async def _main_async(live: bool) -> int:
    scenarios = load_scenarios()
    if live:
        scenarios = [s for s in scenarios if "smoke" in s.tags] or scenarios
    outcomes, usages = await _run(scenarios, _settings_for(live))
    summary = summarize(outcomes, usages)
    gate_rows = evaluate_gate(summary.metrics, load_thresholds())
    write_reports(summary, outcomes, gate_rows)
    render(Console(), summary, gate_rows)
    passed = all(row[3] for row in gate_rows)
    Console().print("[green]GATE PASS[/]" if passed else "[red]GATE FAIL[/]")
    return 0 if passed else 1


def main() -> int:
    parser = argparse.ArgumentParser(description="Run the agent-quality-lab evaluation gate.")
    parser.add_argument(
        "--live", action="store_true", help="use the real Claude API on the smoke subset"
    )
    args = parser.parse_args()
    return asyncio.run(_main_async(args.live))


if __name__ == "__main__":
    raise SystemExit(main())
